export function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';

  localStorage.setItem('zunix_lang', lang);
  document.documentElement.setAttribute('lang', lang);
  
  // RTL support for Arabic
  if (lang === 'ar') {
    document.documentElement.setAttribute('dir', 'rtl');
    document.body.classList.add('rtl-mode');
  } else {
    document.documentElement.setAttribute('dir', 'ltr');
    document.body.classList.remove('rtl-mode');
  }

  // Translate all DOM elements with data-i18n
  const dict = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Update language picker labels & flags
  const flagMap = {
    en: "https://flagcdn.com/w40/gb.png",
    de: "https://flagcdn.com/w40/de.png",
    fr: "https://flagcdn.com/w40/fr.png",
    ar: "https://flagcdn.com/w40/sa.png"
  };

  document.querySelectorAll('.current-lang-label').forEach(el => {
    el.textContent = dict.select_lang;
  });

  document.querySelectorAll('.current-lang-flag').forEach(el => {
    el.style.backgroundImage = `url('${flagMap[lang]}')`;
  });

  // Close any open details menus
  document.querySelectorAll('.lang-dropdown details').forEach(d => {
    d.removeAttribute('open');
  });

  // Show animated toast notification
  showLangToast(dict.select_lang);
}

function showLangToast(langName) {
  const existing = document.getElementById('lang-toast');
  if (existing) existing.remove();

  const toast = document.createElement('div');
  toast.id = 'lang-toast';
  toast.className = 'zunix-toast';
  toast.innerHTML = `<span>🌐</span> Language switched to <strong>${langName}</strong>`;
  document.body.appendChild(toast);

  setTimeout(() => {
    toast.style.transition = 'opacity 0.4s ease, transform 0.4s ease';
    toast.style.opacity = '0';
    toast.style.transform = 'translateY(10px)';
    setTimeout(() => toast.remove(), 400);
  }, 2500);
}

export function initI18n() {
  const saved = localStorage.getItem('zunix_lang') || 'en';
  setLanguage(saved);

  // Bind click handlers for all language triggers
  document.addEventListener('click', (e) => {
    const trigger = e.target.closest('[data-switch-lang]');
    if (trigger) {
      e.preventDefault();
      const lang = trigger.getAttribute('data-switch-lang');
      setLanguage(lang);
    }
  });
}

// Attach to window for global access
if (typeof window !== 'undefined') {
  window.ZunixI18n = { setLanguage, initI18n, translations };
}

// Auto-run if loaded
if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n);
  } else {
    initI18n();
  }
}

